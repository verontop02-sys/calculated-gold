#!/bin/bash
# Чинит /api на reaktivo.pro (и остальных), без /opt/reaktivo/src.
# Вставить на VPS целиком одним блоком.
set -euo pipefail

mkdir -p /etc/nginx/snippets /var/www/reaktivo-pro /var/www/reaktivo-ru

# ── snippet: Render (сейчас боевой upstream) ──
cat >/etc/nginx/snippets/render-proxy.conf <<'EOF'
proxy_pass https://calculated-gold.onrender.com;
proxy_http_version 1.1;
proxy_set_header Host calculated-gold.onrender.com;
proxy_set_header X-Real-IP $remote_addr;
proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
proxy_set_header X-Forwarded-Proto $scheme;
proxy_set_header X-Forwarded-Host $host;
proxy_set_header Upgrade $http_upgrade;
proxy_set_header Connection $connection_upgrade;
proxy_ssl_server_name on;
proxy_ssl_name calculated-gold.onrender.com;
proxy_read_timeout 300s;
proxy_send_timeout 300s;
proxy_connect_timeout 60s;
proxy_buffering off;
proxy_cache off;
proxy_hide_header Alt-Svc;
add_header Alt-Svc "clear" always;
EOF

# ── snippet: local Node (если поднят :8787) ──
cat >/etc/nginx/snippets/local-api-proxy.conf <<'EOF'
proxy_pass http://127.0.0.1:8787;
proxy_http_version 1.1;
proxy_set_header Host $host;
proxy_set_header X-Real-IP $remote_addr;
proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
proxy_set_header X-Forwarded-Proto $scheme;
proxy_set_header X-Forwarded-Host $host;
proxy_set_header Upgrade $http_upgrade;
proxy_set_header Connection $connection_upgrade;
proxy_read_timeout 300s;
proxy_send_timeout 300s;
proxy_connect_timeout 60s;
proxy_buffering off;
proxy_cache off;
proxy_hide_header Alt-Svc;
add_header Alt-Svc "clear" always;
EOF

mkdir -p /etc/nginx/conf.d
cat >/etc/nginx/conf.d/00-websocket-map.conf <<'EOF'
map $http_upgrade $connection_upgrade {
    default upgrade;
    ''      close;
}
EOF

API_SNIP=snippets/render-proxy.conf
if curl -fsS -m 4 http://127.0.0.1:8787/api/health >/dev/null 2>&1; then
  API_SNIP=snippets/local-api-proxy.conf
  echo "upstream: local :8787"
else
  echo "upstream: Render"
fi

# Бэкап текущих сайтов
TS=$(date +%s)
mkdir -p /root/nginx-bak-$TS
cp -a /etc/nginx/sites-enabled /root/nginx-bak-$TS/ 2>/dev/null || true
cp -a /etc/nginx/sites-available /root/nginx-bak-$TS/ 2>/dev/null || true

# Канон: отдельный server на каждый hostname, /api и /sb всегда в proxy
cat >/etc/nginx/sites-available/reaktivo-sites.conf <<EOF
# generated by vps-fix-pro-api.sh

server {
    listen 80;
    listen [::]:80;
    server_name reaktivo.pro www.reaktivo.pro;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://reaktivo.pro\$request_uri; }
}
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name reaktivo.pro;
    ssl_certificate /etc/letsencrypt/live/reaktivo.pro/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/reaktivo.pro/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
    client_max_body_size 50m;
    root /var/www/reaktivo-pro;
    index index.html;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location /api/ { include $API_SNIP; }
    location = /sb { include $API_SNIP; }
    location /sb/ { include $API_SNIP; }
    location = /index.html {
        add_header Cache-Control "no-cache, no-store, must-revalidate" always;
        try_files \$uri =404;
    }
    location /assets/ {
        add_header Cache-Control "public, max-age=31536000, immutable" always;
        try_files \$uri =404;
    }
    location / { try_files \$uri \$uri/ /index.html; }
}

server {
    listen 80;
    listen [::]:80;
    server_name pro.reaktivo.ru;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://pro.reaktivo.ru\$request_uri; }
}
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name pro.reaktivo.ru;
    ssl_certificate /etc/letsencrypt/live/pro.reaktivo.ru/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/pro.reaktivo.ru/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
    client_max_body_size 50m;
    root /var/www/reaktivo-pro;
    index index.html;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location /api/ { include $API_SNIP; }
    location = /sb { include $API_SNIP; }
    location /sb/ { include $API_SNIP; }
    location = /index.html {
        add_header Cache-Control "no-cache, no-store, must-revalidate" always;
        try_files \$uri =404;
    }
    location /assets/ {
        add_header Cache-Control "public, max-age=31536000, immutable" always;
        try_files \$uri =404;
    }
    location / { try_files \$uri \$uri/ /index.html; }
}

server {
    listen 80;
    listen [::]:80;
    server_name reaktivo.ru www.reaktivo.ru;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://reaktivo.ru\$request_uri; }
}
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name reaktivo.ru www.reaktivo.ru;
    ssl_certificate /etc/letsencrypt/live/reaktivo.ru/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/reaktivo.ru/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
    client_max_body_size 50m;
    root /var/www/reaktivo-ru;
    index index.html;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location /api/ { include $API_SNIP; }
    location = /sb { include $API_SNIP; }
    location /sb/ { include $API_SNIP; }
    location = /index.html {
        add_header Cache-Control "no-cache, no-store, must-revalidate" always;
        try_files \$uri =404;
    }
    location /assets/ {
        add_header Cache-Control "public, max-age=31536000, immutable" always;
        try_files \$uri =404;
    }
    location / { try_files \$uri \$uri/ /index.html; }
}

server {
    listen 80;
    listen [::]:80;
    server_name api.reaktivo.ru;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://api.reaktivo.ru\$request_uri; }
}
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name api.reaktivo.ru;
    ssl_certificate /etc/letsencrypt/live/pro.reaktivo.ru/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/pro.reaktivo.ru/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
    client_max_body_size 50m;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { include $API_SNIP; }
}
EOF

# Включаем канон, выключаем конфликтующие старые site-файлы (кроме default/acme)
ln -sfn /etc/nginx/sites-available/reaktivo-sites.conf /etc/nginx/sites-enabled/reaktivo-sites.conf
for f in /etc/nginx/sites-enabled/*; do
  base=$(basename "$f")
  case "$base" in
    reaktivo-sites.conf|default) continue ;;
  esac
  # если внутри есть наши server_name — отключаем, чтобы не дублировать
  if grep -qE 'server_name.*(reaktivo\.pro|pro\.reaktivo\.ru|reaktivo\.ru|api\.reaktivo\.ru)' "$f" 2>/dev/null; then
    echo "disable duplicate $f"
    rm -f "$f"
  fi
done

# Серты должны существовать
for live in reaktivo.pro pro.reaktivo.ru reaktivo.ru; do
  if [[ ! -f /etc/letsencrypt/live/$live/fullchain.pem ]]; then
    echo "WARN: нет сертификата $live — nginx -t может упасть"
    ls /etc/letsencrypt/live/ || true
  fi
done

nginx -t
systemctl reload nginx

echo
echo "=== проверка Host: reaktivo.pro /api/health ==="
curl -sS -m 15 -H 'Host: reaktivo.pro' http://127.0.0.1/api/health || true
echo
curl -sk -m 20 -o /tmp/pro-api.json -w "https_pro %{http_code} %{content_type}\n" https://reaktivo.pro/api/health || echo "https_pro FAIL"
head -c 120 /tmp/pro-api.json 2>/dev/null; echo
curl -sk -m 15 -o /tmp/pru-api.json -w "https_pru %{http_code} %{content_type}\n" https://pro.reaktivo.ru/api/health || true
head -c 120 /tmp/pru-api.json 2>/dev/null; echo

echo
echo "Готово. Панель: https://pro.reaktivo.ru/pro?staff"
echo "Бэкап nginx: /root/nginx-bak-$TS"
